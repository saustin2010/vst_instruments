#!/usr/bin/env python3
"""[FX] Incipience OUT: writes params.json, layout.conf and build/skin.json (the artwork's spec), in Incipience's look.

    python3 mpc/gen.py
    docker run --rm -v "$REPO:$REPO" -w "$PWD" mpc-vst-html-art python3 mpc/art.py build/skin.json

(from the plugin folder, with REPO the repo root). The parameter order is the VST index MPC saves projects and Q-Links
by: append new parameters at the end.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NOUT = 11
INST = ["KICK", "MBRANE", "CL HAT", "OP HAT", "CLAP", "RIM", "CRASH", "RIDE", "X1", "X2", "FM"]


def params():
    return [
        dict(key="out", name="OUT", options=["OUT %d" % o for o in range(1, NOUT + 1)], default="OUT 1"),
        dict(key="thru", name="THRU", options=["OFF", "ON"], default="ON"),   # on: the track's own audio too
        dict(key="status", name="STATUS", min=0, max=0, display="string", type="readout"),
    ]


# Incipience's screen colours (its layout.conf)
THEME = """theme_accent=d32a2a
theme_accent_hi=ff3333
theme_bg=efede6
theme_box=e4e1d8
theme_btn_bg=2c2c2c
theme_btn_text=e5e5e5
theme_display_ink=ffffff
theme_ink=141414
theme_ink_dim=3a3a3a
theme_ink_faint=8d8d8d
theme_knob_dot=ffffff
theme_knob_face=151515
theme_knob_ring=2a2a2a
theme_lcd=0b0b0b
theme_line=141414
theme_panel=efede6
theme_seg_active=141414
theme_seg_active_tx=f4f2ec
theme_seg_inactive=dcd8ce
qlink_bounds=column
qlink_box=slot
label_scale=1
focus_ring=1
"""

CSS = """*{box-sizing:border-box}
body{margin:0;width:1280px;height:628px;overflow:hidden;position:relative;font-family:'Inter',sans-serif;
background:linear-gradient(180deg,#f3f1ea 0%,#efede6 40%,#e8e5dc 100%)}
.a{position:absolute}
.t{position:absolute;white-space:nowrap;line-height:1}
"""


def h_text(x, y, s, size=11, weight=800, color="#141414", spacing=0.12, w=None, align="left"):
    width = "width:%dpx;" % w if w else ""
    return ('<div class="t" style="left:%dpx;top:%dpx;%stext-align:%s;font-size:%dpx;font-weight:%d;letter-spacing:%.2fem;'
            'color:%s">%s</div>' % (x, y - 86, width, align, size, weight, spacing, color, s))


def layout():
    L = ["# [FX] Incipience OUT, generated by mpc/gen.py (do not edit by hand: change gen.py and run it again).", THEME]
    art = {"out": os.path.join(ROOT, "images", "skin"), "css": CSS, "bgs": [], "segs": []}

    def seg(lit, w, h):
        name = "seg_%s_%dx%d" % ("on" if lit else "off", w, h)
        if not any(s["name"] == name for s in art["segs"]):
            art["segs"].append({"name": name, "w": w, "h": h, "lit": lit})
        return "images/skin/%s.png" % name

    L.append("[tab OUT]")
    L.append("art file=images/skin/bg_out.png x=0 y=86 w=1280 h=628")
    # the red stripe and the name, as on Incipience's pages
    html = '<div class="a" style="left:22px;right:22px;top:12px;height:8px;background:#d32a2a"></div>'
    html += ('<div class="a" style="left:40px;top:38px;width:14px;height:26px;border-radius:7px;background:#d32a2a"></div>'
             + h_text(66, 86 + 38, "INCIPIENCE OUT", 27, 900, spacing=0.28)
             + h_text(68, 86 + 74, "PLAYS ONE OF INCIPIENCE'S OUTS ON THIS TRACK", 9.5, 800, spacing=0.22))
    html += h_text(40, 202, "OUT", 11, 800) + '<div class="a" style="left:40px;right:40px;top:%dpx;height:1px;background:#141414"></div>' % (218 - 86)
    sw, sh, gap = 98, 64, 2   # the skin builder's enum_h: 2 px apart (shadow_skin.py seg_rects)
    x0 = 640 - (NOUT * sw + (NOUT - 1) * gap) // 2
    L.append('enum_h cx=640 cy=262 label="" key=out sw=%d sh=%d img=%s img_on=%s' % (sw, sh, seg(0, sw, sh), seg(1, sw, sh)))
    for o in range(NOUT):   # who's on each OUT to start with
        html += h_text(x0 + o * (sw + gap), 306, INST[o], 9, 800, "#3a3a3a", 0.06, sw, "center")
    html += h_text(40, 330, "TO START WITH, EACH INSTRUMENT'S OUT IS ITS OWN (INCIPIENCE: MIDI &amp; OUT, SUB-PAGE OUT)", 9,
                   800, "#8d8d8d", 0.1)
    # what's coming in, in a display like the OLED's
    html += ('<div class="a" style="left:240px;top:%dpx;width:800px;height:70px;border-radius:6px;background:#0b0b0b;'
             'border:2px solid #222;box-shadow:inset 0 2px 8px rgba(0,0,0,.9)"></div>' % (366 - 86))
    L.append("readout cx=640 cy=401 w=780 h=56 vs=30 ink=accent box=no key=status")
    html += h_text(40, 468, "THRU", 11, 800) + '<div class="a" style="left:40px;right:40px;top:%dpx;height:1px;background:#141414"></div>' % (484 - 86)
    L.append('enum_h cx=640 cy=526 label="" key=thru sw=160 sh=56 img=%s img_on=%s' % (seg(0, 160, 56), seg(1, 160, 56)))
    for i, line in enumerate((
            "WHILE THIS PLAYS AN OUT, ITS INSTRUMENTS LEAVE INCIPIENCE'S OWN MIX (THEIR REVERB AND DELAY SENDS STAY); REMOVE IT AND THEY GO BACK",
            "THRU ON: THIS TRACK'S OWN AUDIO PLAYS TOO (OFF: THE OUT ALONE). THE OUT IS A BLOCK (2.9 MS) LATE; INCIPIENCE WAITS FOR IT")):
        html += h_text(40, 590 + 24 * i, line, 9.5, 800, "#3a3a3a" if i == 0 else "#8d8d8d", 0.08)
    art["bgs"].append({"name": "bg_out", "html": html})
    L.append('qlinks "OUT" = out,thru')
    L.append("")
    open(os.path.join(ROOT, "layout.conf"), "w").write("\n".join(L) + "\n")
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    json.dump(art, open(os.path.join(ROOT, "build", "skin.json"), "w"), indent=1)


if __name__ == "__main__":
    P = params()
    json.dump({"name": "Incipience OUT", "params": P}, open(os.path.join(ROOT, "params.json"), "w"), indent=1)
    layout()
    print("params.json: %d parameters; layout.conf; build/skin.json (then mpc/art.py)" % len(P))
