#!/usr/bin/env python3
"""Percolator: writes params.json (what MPC sees), src/params_def.h (the engine's table, same order) and layout.conf.

    python3 mpc/gen.py            (from the plugin folder, or anywhere: paths are relative to this file)

The parameter order is the VST index MPC saves projects and Q-Links by: append new parameters at the end.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

KNOBS = [("tune", "TUNE"), ("decay", "DECAY"), ("p1", "PARAM 1"), ("p2", "PARAM 2"),
         ("cutoff", "CUTOFF"), ("drive", "DRIVE"), ("fx", "FX SEND"), ("level", "LEVEL")]
ALGOS = {1: ["FOLD", "WAVE", "RES BD"], 2: ["FOLD", "WAVE", "FM"], 3: ["SNARE", "SLAP", "TOM"],
         4: ["NOISE", "METAL", "SAMPLE"]}
DEPTHS = ["OFF"] + ["%d%%" % (10 * i) for i in range(1, 9)]
WAVES = ["SINE", "TRI", "RAMP", "SAW", "SQUARE", "S&H", "DRIFT"]

# the Init kit (also the engine's defaults): 0..100 for knobs, option index for switches
INIT = {
    1: dict(tune=38, decay=22, p1=18, p2=34, cutoff=60, drive=18, fx=0, level=85, algo=0, mode=0, vcf=2),
    2: dict(tune=48, decay=20, p1=35, p2=25, cutoff=75, drive=10, fx=12, level=70, algo=2, mode=0, vcf=2),
    3: dict(tune=45, decay=18, p1=55, p2=35, cutoff=80, drive=15, fx=10, level=75, algo=0, mode=0, vcf=2),
    4: dict(tune=55, decay=6, p1=10, p2=0, cutoff=45, drive=0, fx=0, level=60, algo=0, mode=0, vcf=0),
}


def params():
    P = []

    def knob(key, name, default, **kw):
        P.append(dict(key=key, name=name, min=0, max=100, default=default, **kw))

    def opts(key, name, options, default=0, **kw):
        P.append(dict(key=key, name=name, options=options, default=options[default], **kw))

    # clamped: the engine holds KIT to the kits it has loaded (8 built in + the packs found)
    P.append(dict(key="kit", name="KIT", type="stepper", min=0, max=511, step=1, default=0, display="int", clamped=True))
    P.append(dict(key="kit_prev", name="PREV KIT", momentary=True, step_of="kit", step_delta=-1))
    P.append(dict(key="kit_next", name="NEXT KIT", momentary=True, step_of="kit", step_delta=1))
    P.append(dict(key="kit_name", name="KIT NAME", min=0, max=0, display="string", type="readout"))
    for v in range(1, 5):
        for k, n in KNOBS:
            extra = {}
            if k in ("p1", "p2"):
                extra["dynamic_name"] = True
            if k in ("tune", "decay", "p1", "p2", "cutoff"):
                extra["dynamic_display"] = True
            knob("v%d_%s" % (v, k), "V%d %s" % (v, n), INIT[v][k], **extra)
        opts("v%d_algo" % v, "V%d ALGO" % v, ALGOS[v], INIT[v]["algo"])
        opts("v%d_mode" % v, "V%d MODE" % v, ["1", "2", "3"], INIT[v]["mode"], dynamic_display=True)
        opts("v%d_vcf" % v, "V%d VCF" % v, ["HP", "BP", "LP"], INIT[v]["vcf"])
    knob("fx_time", "BBD TIME", 45, dynamic_display=True)
    knob("fx_feedback", "FEEDBACK", 35)
    knob("fx_rate", "BBD LFO RATE", 30, dynamic_display=True)
    knob("fx_depth", "BBD MOD DEPTH", 10)
    opts("fx_range", "BBD RANGE", ["SHORT", "LONG"], 1)
    opts("fx_colour", "BBD COLOUR", ["DARK", "BRIGHT"], 0)
    knob("volume", "VOLUME", 71)
    knob("comp_thresh", "COMP THRESH", 0, dynamic_display=True)
    knob("comp_amt", "COMP AMOUNT", 0)
    knob("lfo_speed", "LFO SPEED", 40, dynamic_display=True)
    opts("lfo_wave", "LFO WAVE", WAVES, 0)
    knob("lfo_level", "MOD LEVEL", 100)
    opts("keys", "KEYS", ["OFF", "V1", "V2", "V3", "V4"], 0)
    for v in range(1, 5):
        for k, n in KNOBS:
            opts("v%d_m_%s" % (v, k), "V%d MOD %s" % (v, n), DEPTHS, 0)
    return P


def write_header(P):
    lines = ["/* generated by mpc/gen.py: do not edit (change gen.py and run it) */", "#pragma once",
             "/* kind: 0 = knob 0..100, 1 = option list (value = index), 2 = kit number, 3 = not a stored value */",
             "typedef struct { const char *key; int kind; int nopts; float def; } pdef_t;",
             "static const pdef_t PDEF[] = {"]
    enum = []
    for i, p in enumerate(P):
        if "options" in p:
            kind, n, d = 1, len(p["options"]), p["options"].index(p["default"])
        elif p["key"] == "kit":
            kind, n, d = 2, 0, 0
        elif p.get("momentary") or p.get("display") == "string":
            kind, n, d = 3, 0, 0
        else:
            kind, n, d = 0, 0, p["default"]
        lines.append('    {"%s", %d, %d, %.1ff},' % (p["key"], kind, n, d))
        enum.append("P_%s = %d," % (p["key"].upper(), i))
    lines += ["};", "enum {"] + ["    " + e for e in enum] + ["    NP = %d" % len(P), "};"]
    lines += ["/* per-voice block: v%d_tune is P_V1_TUNE + 11 * (v - 1) */", "#define VSTRIDE 11",
              "#define MSTRIDE 8"]
    open(os.path.join(ROOT, "src", "params_def.h"), "w").write("\n".join(lines) + "\n")


