#!/usr/bin/env python3
"""[FX] Percolator OUT: writes params.json, layout.conf and build/skin.json (the artwork's spec).

    python3 mpc/gen.py
    docker run --rm -v "$REPO:$REPO" -w "$PWD" mpc-vst-html-art python3 ../mpc/skin.py build/skin.json

(from the plugin folder, with REPO the repo root; the artwork is drawn by Percolator's mpc/skin.py, in the folder
above, as this plugin ships in Percolator's release). The parameter
order is the VST index MPC saves projects and Q-Links by: append new parameters at the end.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(os.path.dirname(ROOT)))   # originals/percolator/percolatorout -> the repo
COL = "#a07bff"   # Percolator's MASTER colour


def params():
    return [
        dict(key="out", name="OUT", options=["OUT 1", "OUT 2", "OUT 3", "OUT 4"], default="OUT 1"),
        dict(key="thru", name="THRU", options=["OFF", "ON"], default="ON"),   # on: the track's own audio too
        dict(key="status", name="STATUS", min=0, max=0, display="string", type="readout"),
    ]


THEME = """theme_bg=0b0a10
theme_panel=15141c
theme_line=34323f
theme_ink=f3f0ff
theme_ink_dim=aba7c4
theme_ink_faint=6a6782
theme_accent=b48cff
theme_accent_hi=d9c6ff
theme_box=0d0c13
theme_lcd=07060b
theme_seg_active=b48cff
theme_seg_active_tx=0b0a10
theme_seg_inactive=24232e
theme_btn_bg=2a2838
theme_btn_text=f3f0ff
theme_knob_face=26252f
theme_knob_ring=3a3848
theme_knob_dot=b48cff
theme_display_bezel=050407
theme_display_bg=0d0a10
theme_display_cell=21160f
theme_display_ink=ffb13d
theme_display_off=2b1c10
art_css=percolatorout.css
qlink_bounds=column
qlink_box=slot
label_scale=1
focus_ring=1
"""

CSS = """*{box-sizing:border-box}
body{margin:0;width:1280px;height:628px;overflow:hidden;position:relative;font-family:"Titillium Web",sans-serif;
background:radial-gradient(ellipse 85% 75% at 50% 35%,#18141f 0%,#0c0b11 55%,#060609 100%)}
body:after{content:"";position:absolute;inset:0;background:repeating-linear-gradient(0deg,rgba(255,255,255,.014) 0 1px,
transparent 1px 3px)}
.a{position:absolute}
.t{position:absolute;white-space:nowrap;line-height:1}
"""


def rgba(c, a):
    c = c.lstrip("#")
    return "rgba(%d,%d,%d,%.3f)" % (int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16), a)


def h_panel(x, y, w, h, c, title, sub=""):   # as Percolator's (layout y in, artwork y out)
    y -= 86
    o = ('<div class="a" style="left:%dpx;top:%dpx;width:%dpx;height:%dpx;border-radius:16px;'
         'background:linear-gradient(180deg,#1b1a25 0%%,#111018 100%%);border:1.5px solid %s;'
         'box-shadow:0 0 24px %s,inset 0 1px 0 rgba(255,255,255,.06)"></div>' % (x, y, w, h, rgba(c, .6), rgba(c, .25)))
    o += ('<div class="a" style="left:%dpx;top:%dpx;width:%dpx;height:3px;border-radius:2px;'
          'background:linear-gradient(90deg,%s,%s 60%%,transparent);box-shadow:0 0 10px %s"></div>'
          % (x + 16, y + 1, w - 32, c, rgba(c, .35), rgba(c, .8)))
    o += ('<div class="t" style="left:%dpx;top:%dpx;display:flex;align-items:baseline;gap:14px">'
          '<span style="font-size:22px;font-weight:700;letter-spacing:.22em;color:%s;text-shadow:0 0 12px %s">%s</span>'
          '<span style="font-size:13px;font-weight:600;letter-spacing:.16em;color:#8f8ba8">%s</span></div>'
          % (x + 20, y + 14, c, rgba(c, .7), title, sub))
    return o


def h_ctext(cx, y, s, c="#aba7c4", size=13, w=1200):
    return ('<div class="t" style="left:%dpx;top:%dpx;width:%dpx;text-align:center;font-size:%dpx;font-weight:600;'
            'letter-spacing:.14em;color:%s">%s</div>' % (cx - w // 2, y - 86, w, size, c, s))


def layout():
    L = ["# [FX] Percolator OUT, generated by mpc/gen.py (do not edit by hand: change gen.py and run it again).", THEME]
    art = {"out": os.path.join(ROOT, "images", "skin"), "css": CSS, "display_frames": 32,
           "fonts": os.path.join(REPO, "framework", "mpc-vst-plugins", "tools",
                                 "html_art", "fonts"),
           "bgs": [], "knobs": [], "segs": [], "displays": []}

    def seg(lit, w, h):
        name = "seg_%s_%dx%d" % ("on" if lit else "off", w, h)
        if not any(s["name"] == name for s in art["segs"]):
            art["segs"].append({"name": name, "w": w, "h": h, "color": COL if lit else None})
        return "images/skin/%s.png" % name

    L.append("[tab OUT]")
    L.append("art file=images/skin/bg_out.png x=0 y=86 w=1280 h=628")
    html = h_panel(8, 94, 1264, 612, COL, "PERCOLATOR OUT", "PLAYS ONE OF PERCOLATOR'S OUTS ON THIS TRACK")
    html += h_ctext(640, 168, "OUT")
    L.append("enum_h cx=640 cy=236 label=\"\" key=out sw=240 sh=84 img=%s img_on=%s" % (seg(0, 240, 84), seg(1, 240, 84)))
    # what's coming in: the voices the main Percolator sends to this OUT, or why there's nothing
    html += ('<div class="a" style="left:%dpx;top:%dpx;width:%dpx;height:%dpx;border-radius:10px;background:#050508;'
             'border:1px solid %s;box-shadow:inset 0 2px 12px #000,0 0 14px %s"></div>'
             % (240, 300 - 86, 800, 70, rgba(COL, .4), rgba(COL, .14)))
    L.append("readout cx=640 cy=335 w=780 h=56 vs=30 ink=accent box=no key=status")
    html += h_ctext(640, 412, "THRU")
    L.append("enum_h cx=640 cy=470 label=\"\" key=thru sw=160 sh=60 img=%s img_on=%s" % (seg(0, 160, 60), seg(1, 160, 60)))
    for i, line in enumerate((
            "ON PERCOLATOR (MAIN KIT), EACH VOICE'S OUT IS ON ITS MIDI &amp; OUT PAGE: VOICE 1 STARTS ON OUT 1, AND SO ON",
            "WHILE THIS PLAYS AN OUT, ITS VOICES LEAVE PERCOLATOR'S OWN MIX; REMOVE IT AND THEY GO BACK",
            "THRU ON: THIS TRACK'S OWN AUDIO PLAYS TOO (OFF: THE OUT ALONE). THE OUT IS A BLOCK (2.9 MS) LATE; PERCOLATOR WAITS FOR IT")):
        html += h_ctext(640, 556 + 26 * i, line, "#8f8ba8" if i < 2 else "#6a6782", 12)
    art["bgs"].append({"name": "bg_out", "html": html})
    L.append('qlinks "OUT" = out,thru')
    L.append("")
    open(os.path.join(ROOT, "layout.conf"), "w").write("\n".join(L) + "\n")
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    json.dump(art, open(os.path.join(ROOT, "build", "skin.json"), "w"), indent=1)


if __name__ == "__main__":
    P = params()
    json.dump({"name": "Percolator OUT", "params": P}, open(os.path.join(ROOT, "params.json"), "w"), indent=1)
    layout()
    print("params.json: %d parameters; layout.conf; build/skin.json (then ../mpc/skin.py)" % len(P))
