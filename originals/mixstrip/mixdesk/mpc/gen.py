#!/usr/bin/env python3
"""[UTIL] Mix Desk: writes params.json, layout.conf and build/skin.json (the artwork's spec).

    python3 mpc/gen.py
    docker run --rm -v "$REPO:$REPO" -w "$PWD" mpc-vst-html-art python3 ../mpc/skin.py build/skin.json

(from the plugin folder, with REPO the repo root; the drawing helpers and mpc/skin.py are Mix Strip's, in the folder
above, as with Mix Bus). The parameter order is the VST index MPC saves projects and Q-Links by: append new
parameters at the end.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(os.path.dirname(ROOT), "mpc"))
import gen as strip  # noqa: E402  Mix Strip's mpc/gen.py: the look, the helpers

COL = strip.COL
COLS = 16     # the columns: the controller's page 1 (1-8, MIDI CH) and page 2 (9-16, MIDI CH + 1)
TRACKS = 16   # the MPC tracks a column can play
OUT_CC = 102  # mixshm.h MIX_OUT_CC: track t's volume CC OUT_CC + t - 1 on channel 1, its Track Mute on channel 2


def params():
    ro = dict(min=0, max=0, display="string", type="readout")
    P = [
        dict(key="status", name="STATUS", **ro),   # index 0: MPC nudges it
        dict(key="mode", name="LEVEL+MUTE", options=["STRIPS", "MPC MIXER"], default="STRIPS"),
        dict(key="button2", name="BUTTON 2", options=["CUE", "SEND KILL"], default="CUE"),
        dict(key="midi_ch", name="MIDI CH", min=1, max=15, default=1, display="int"),
        dict(key="mute_out", name="MUTE OUT", options=["ON/OFF", "PRESS"], default="ON/OFF"),
    ]
    # each column's track: a grid of buttons 1-16 and OFF; each option sends its track number (OFF 0)
    P += [dict(key="col%d" % c, name="COLUMN %d" % c, options=["TRACK %d" % t for t in range(1, TRACKS + 1)] + ["OFF"],
               values=list(range(1, TRACKS + 1)) + [0], default="TRACK %d" % c) for c in range(1, COLS + 1)]
    P += [dict(key="midi_ch_prev", name="MIDI CH DOWN", momentary=True, step_of="midi_ch", step_delta=-1),
          dict(key="midi_ch_next", name="MIDI CH UP", momentary=True, step_of="midi_ch", step_delta=1)]
    for c in range(1, COLS + 1):   # what each column is doing
        P += [dict(key="lv%d" % c, name="COLUMN %d LEVEL" % c, **ro),
              dict(key="st%d" % c, name="COLUMN %d SW" % c, **ro),
              dict(key="sd%d" % c, name="COLUMN %d SENDS" % c, **ro)]
    return P


def layout():
    art = strip.Art(ROOT)
    L = ["# [UTIL] Mix Desk, generated by mpc/gen.py (do not edit by hand: change gen.py and run it again).",
         strip.THEME.replace("mixstrip.css", "mixdesk.css")]

    # ---- MIX 1-8 and MIX 9-16: eight columns each ----
    for page in range(2):
        tab = "MIX %d-%d" % (page * 8 + 1, page * 8 + 8)
        bg = "bg_mix%d" % (page + 1)
        L += ["", "[tab %s]" % tab, "art file=images/skin/%s.png x=0 y=86 w=1280 h=628" % bg]
        html = strip.h_panel(8, 94, 1264, 612, COL, "MIX DESK", "%s: THE CONTROLLER'S %s PAGE, MIDI CH%s. PICK THE TRACK EACH COLUMN PLAYS"
                             % (tab, "FIRST" if not page else "SECOND", "" if not page else " + 1"))
        for i in range(8):
            c = page * 8 + i + 1
            x = 24 + i * 154
            cx = x + 73
            html += ('<div class="a" style="left:%dpx;top:%dpx;width:146px;height:420px;border-radius:12px;'
                     'background:#0a0e0f;border:1px solid %s;box-shadow:inset 0 2px 14px #000"></div>'
                     % (x, 146 - 86, strip.rgba(COL, .28)))
            html += strip.h_ctext(cx, 158, "COLUMN %d" % c, "#a3b8b5", 13, 140)
            html += strip.h_ctext(cx, 176, "PLAYS TRACK", "#627573", 10, 140)
            L.append('enum_h cx=%d cy=206 label="" key=col%d sw=32 sh=30 rows=5 options="%s" img=%s img_on=%s'
                     % (cx, c, ",".join([str(t) for t in range(1, TRACKS + 1)] + ["OFF"]), art.seg(0, 32, 30), art.seg(1, 32, 30)))
            html += strip.h_glass(cx, 386, 134, 38, COL)
            L.append("readout cx=%d cy=386 w=128 h=32 vs=21 ink=ink box=0 key=lv%d" % (cx, c))
            html += strip.h_ctext(cx, 414, "MUTE · BUTTON 2", "#627573", 10, 140)
            L.append("readout cx=%d cy=438 w=134 h=26 vs=16 ink=accent box=0 key=st%d" % (cx, c))
            html += strip.h_ctext(cx, 462, "SENDS", "#627573", 10, 140)
            L.append("readout cx=%d cy=486 w=134 h=26 vs=16 ink=dim box=0 key=sd%d" % (cx, c))
            html += strip.h_ctext(cx, 516, "FADER %d · MUTE %d" % (77 + i, 104 + i), "#627573", 10, 140)
            html += strip.h_ctext(cx, 534, "BUTTON 2 CC %d" % (112 + i), "#627573", 10, 140)
            html += strip.h_ctext(cx, 552, "ON MIDI CH%s" % ("" if not page else " + 1"), "#627573", 10, 140)
        html += strip.h_glass(640, 612, 1220, 52, COL)
        L.append("readout cx=640 cy=612 w=1200 h=46 vs=26 ink=accent box=0 key=status")
        for k, line in enumerate((
                "EACH COLUMN PLAYS THE MPC TRACK SET HERE. A TRACK'S MIX STRIP (ITS SENDS, KNOB 3, BUTTON 2) FOLLOWS ITS COLUMN: SET THE STRIP'S TRACK TO THE TRACK IT'S ON",
                "LEVEL + MUTE ON MPC MIXER (SETUP): THE FADERS AND MUTES ARE MPC'S OWN, ON ITS MIXER AND TRACK MUTE PAGES, AFTER ONE MIDI LEARN")):
            html += strip.h_ctext(640, 654 + 22 * k, line, "#8aa09d" if k == 0 else "#627573", 11, 1240)
        art.spec["bgs"].append({"name": bg, "html": html})
        L.append('qlinks "%s" = ' % tab + ",".join("col%d" % c for c in range(page * 8 + 1, page * 8 + 9)))

    # ---- SETUP: who does LEVEL and MUTE, BUTTON 2, the channel; the MIDI Learn chart ----
    L += ["", "[tab SETUP]", "art file=images/skin/bg_setup.png x=0 y=86 w=1280 h=628"]
    html = strip.h_panel(8, 94, 1264, 612, COL, "MIX DESK", "SETUP")
    html += strip.h_box(24, 146, 400, 420, COL)
    for cy, key, title in ((206, "mode", "LEVEL + MUTE"), (300, "button2", "BUTTON 2"), (488, "mute_out", "MUTE OUT")):
        html += strip.h_ctext(224, cy - 40, title)
        L.append('enum_h cx=224 cy=%d label="" key=%s sw=170 sh=50 img=%s img_on=%s'
                 % (cy, key, art.seg(0, 170, 50), art.seg(1, 170, 50)))
    html += strip.h_ctext(224, 354, "MIDI CH (THE CONTROLLER'S COLUMNS)")
    L.append('stepper cx=224 cy=394 w=300 h=56 label="" key=midi_ch label_align=center')
    html += strip.h_ctext(224, 530, "PRESS: IF MPC'S LEARNED MUTE FLIPS ON EVERY MESSAGE", "#627573", 10, 380)

    html += strip.h_box(440, 146, 816, 420, COL)
    learn = [
        ("MPC MIXER: MPC'S OWN FADERS AND TRACK MUTES", "#a6f0e7", 15),
        ("LEARN THEM ONCE, IN A PROJECT YOU SAVE AS YOUR TEMPLATE", "#a3b8b5", 12),
        ("", None, 0),
        ("1. PREFERENCES, MIDI: \"MIX DESK MIDI OUT\" CONTROL ON, TRACK OFF.", "#eefaf8", 12),
        ("    THE CONTROLLER: CONTROL OFF (SO MPC LEARNS THE DESK, NOT THE CONTROLLER)", "#a3b8b5", 11),
        ("2. HERE: LEVEL + MUTE = MPC MIXER, COLUMN n = TRACK n (THE START)", "#eefaf8", 12),
        ("3. MIDI LEARN: TOUCH TRACK n'S FADER, MOVE FADER n.", "#eefaf8", 12),
        ("    TOUCH TRACK n'S TRACK MUTE, PRESS MUTE n. EVERY TRACK YOU USE, 1 TO 16 (PAGE 2 FOR 9-16)", "#a3b8b5", 11),
        ("4. SAVE AS YOUR TEMPLATE. AFTER THAT, MOVE A COLUMN TO ANY TRACK HERE: NO NEW LEARNING", "#eefaf8", 12),
        ("", None, 0),
        ("WHAT THE DESK SENDS (ITS OWN PORT)", "#a6f0e7", 12),
        ("TRACK t'S VOLUME: CC %d + t - 1 ON CH 1 (TRACKS 1-16: CC %d-%d)" % (OUT_CC, OUT_CC, OUT_CC + TRACKS - 1), "#a3b8b5", 11),
        ("TRACK t'S TRACK MUTE: THE SAME CC ON CH 2 (127 MUTED, 0 NOT)", "#a3b8b5", 11),
    ]
    y = 176
    for text, color, size in learn:
        if text:   # a line starting with spaces is the step above's second line: indented
            html += ('<div class="t" style="left:%dpx;top:%dpx;font-size:%dpx;font-weight:600;letter-spacing:.1em;'
                     'color:%s">%s</div>' % (496 if text.startswith(" ") else 468, y - 86, size, color, text.strip()))
        y += 28 if size >= 15 else 30 if text else 14
    html += strip.h_glass(640, 612, 1220, 52, COL)
    L.append("readout cx=640 cy=612 w=1200 h=46 vs=26 ink=accent box=0 key=status")
    for k, line in enumerate((
            "BUTTON 2 = SEND KILL: EVERY STRIP'S SECOND BUTTON CUTS ITS SENDS (FOR WHEN THE MIXER DOES THE CUE). CUE: AS BEFORE, TO A MIX BUS ON CUE",
            "ONE DESK PER PROJECT, ON THE MASTER'S INSERTS. ITS AUDIO PASSES THROUGH UNTOUCHED")):
        html += strip.h_ctext(640, 654 + 22 * k, line, "#8aa09d" if k == 0 else "#627573", 11, 1240)
    art.spec["bgs"].append({"name": "bg_setup", "html": html})
    L.append('qlinks "SETUP" = mode,button2,midi_ch,mute_out')
    L.append("")
    open(os.path.join(ROOT, "layout.conf"), "w").write("\n".join(L) + "\n")
    open(os.path.join(ROOT, "mixdesk.css"), "w").write(strip.SKIN_CSS)
    art.write()


if __name__ == "__main__":
    P = params()
    json.dump({"name": "Mix Desk", "params": P}, open(os.path.join(ROOT, "params.json"), "w"), indent=1)
    layout()
    print("params.json: %d parameters; layout.conf; build/skin.json (then ../mpc/skin.py)" % len(P))
