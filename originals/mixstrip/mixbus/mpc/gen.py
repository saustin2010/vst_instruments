#!/usr/bin/env python3
"""[UTIL] Mix Bus: writes params.json, layout.conf and build/skin.json (the artwork's spec).

    python3 mpc/gen.py
    docker run --rm -v "$REPO:$REPO" -w "$PWD" mpc-vst-html-art python3 ../mpc/skin.py build/skin.json

(from the plugin folder, with REPO the repo root; the drawing helpers and mpc/skin.py are Mix Strip's, in the folder
above, as this plugin ships in Mix Strip's release). The parameter order is the VST index MPC saves projects and
Q-Links by: append new parameters at the end.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(os.path.dirname(ROOT), "mpc"))
import gen as strip  # noqa: E402  Mix Strip's mpc/gen.py: the look, the helpers

COL = strip.COL


def params():
    return ([
        dict(key="status", name="STATUS", min=0, max=0, display="string", type="readout"),   # index 0: MPC nudges it
        dict(key="bus", name="BUS", options=["CUE", "FX A", "FX B"], default="CUE"),
        dict(key="level", name="LEVEL", min=0, max=100, default=75, dynamic_display=True),
        dict(key="cue_mode", name="CUE MODE", options=["ADD", "SOLO"], default="ADD"),
    ] + [dict(key="t%d" % t, name="TRACK %d" % t, min=0, max=0, display="string", type="readout") for t in range(1, 17)]
      + [dict(key="f%d" % t, name="TRACK %d SW" % t, min=0, max=0, display="string", type="readout") for t in range(1, 17)])


def layout():
    art = strip.Art(ROOT)
    L = ["# [UTIL] Mix Bus, generated by mpc/gen.py (do not edit by hand: change gen.py and run it again).",
         strip.THEME.replace("mixstrip.css", "mixbus.css"), "[tab BUS]",
         "art file=images/skin/bg_bus.png x=0 y=86 w=1280 h=628"]
    html = strip.h_panel(8, 94, 1264, 612, COL, "MIX BUS", "PLAYS ONE BUS OF EVERY MIX STRIP: THE CUE, OR AN FX SEND")

    html += strip.h_box(24, 146, 1232, 170, COL)
    html += strip.h_ctext(270, 166, "BUS")
    L.append('enum_h cx=270 cy=228 label="" key=bus sw=140 sh=72 img=%s img_on=%s'
             % (art.seg(0, 140, 72), art.seg(1, 140, 72)))
    L.append('knob cx=660 cy=226 r=46 label="LEVEL" key=level strip=%s frames=64' % art.knob(46, COL))
    html += strip.h_ctext(1010, 166, "CUE MODE")
    L.append('enum_h cx=1010 cy=228 label="" key=cue_mode sw=140 sh=60 img=%s img_on=%s'
             % (art.seg(0, 140, 60), art.seg(1, 140, 60)))
    html += strip.h_ctext(1010, 272, "ADD: SEVERAL CUES AT ONCE", "#627573", 11, 420)
    html += strip.h_ctext(1010, 290, "SOLO: A NEW CUE TURNS THE OTHERS OFF", "#627573", 11, 420)

    html += strip.h_glass(640, 350, 1220, 46, COL)
    L.append("readout cx=640 cy=350 w=1200 h=40 vs=24 ink=accent box=0 key=status")

    # the overview: every TRACK's strip
    for t in range(16):
        x, y = 24 + (t % 8) * 154, 386 + (t // 8) * 124
        html += ('<div class="a" style="left:%dpx;top:%dpx;width:146px;height:116px;border-radius:10px;'
                 'background:#0a0e0f;border:1px solid %s;box-shadow:inset 0 2px 10px #000"></div>'
                 % (x, y - 86, strip.rgba(COL, .25)))
        html += strip.h_ctext(x + 73, y + 14, "TRACK %d" % (t + 1), "#8aa09d", 12, 140)
        L.append("readout cx=%d cy=%d w=134 h=30 vs=22 ink=ink box=0 key=t%d" % (x + 73, y + 60, t + 1))
        L.append("readout cx=%d cy=%d w=134 h=24 vs=16 ink=accent box=0 key=f%d" % (x + 73, y + 92, t + 1))
    for i, line in enumerate((
            "ON AN EMPTY AUDIO TRACK. CUE: ROUTE THIS TRACK TO YOUR HEADPHONES' OUTPUT · FX A / FX B: THE EFFECT IN THE NEXT INSERT SLOT, FULLY WET",
            "THE BUSES PLAY A BLOCK OR TWO (3 TO 6 MS) AFTER THE STRIPS. THIS TRACK'S OWN AUDIO PASSES THROUGH")):
        html += strip.h_ctext(640, 654 + 22 * i, line, "#8aa09d" if i == 0 else "#627573", 11, 1240)
    art.spec["bgs"].append({"name": "bg_bus", "html": html})
    L.append('qlinks "BUS" = level,bus,cue_mode')
    L.append("")
    open(os.path.join(ROOT, "layout.conf"), "w").write("\n".join(L) + "\n")
    open(os.path.join(ROOT, "mixbus.css"), "w").write(strip.SKIN_CSS)
    art.write()


if __name__ == "__main__":
    P = params()
    json.dump({"name": "Mix Bus", "params": P}, open(os.path.join(ROOT, "params.json"), "w"), indent=1)
    layout()
    print("params.json: %d parameters; layout.conf; build/skin.json (then ../mpc/skin.py)" % len(P))
